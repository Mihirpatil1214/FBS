x = 10 
y = 20

## relational op
#1. ==            exact equal to
print(x == '10')   #integar  ani string doghana chalte 

#2. !=           not equal to
print(x != y)    #integar ani string doghana chalte 

#3. > 
print(x > 5)

#4. >=   (greater than equals to)
print(y >= 10)

#5. < 
print(y <  x)

#6. <=    (less than equals to )
print(y <= 20)
